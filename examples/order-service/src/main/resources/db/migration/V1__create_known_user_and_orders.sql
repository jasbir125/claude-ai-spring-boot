-- Local projection of user-service users, built only from user.user.events.v1 (user-service owns the users).
-- Stores no personal data: order-service only needs to know whether a user may place orders.
CREATE TABLE known_user (
    user_id       BIGINT       NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    user_version  BIGINT       NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_known_user PRIMARY KEY (user_id),
    CONSTRAINT ck_known_user_status CHECK (status IN ('ACTIVE', 'DEACTIVATED')),
    CONSTRAINT ck_known_user_version CHECK (user_version >= 0)
);

-- Order aggregate root. Amounts use the currency's minor units (ISO 4217); NUMERIC(19,4) fits every currency.
CREATE TABLE orders (
    id                   BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    user_id              BIGINT         NOT NULL,
    status               VARCHAR(20)    NOT NULL DEFAULT 'PLACED',
    currency             VARCHAR(3)     NOT NULL,
    total_amount         NUMERIC(19, 4) NOT NULL,
    cancellation_reason  VARCHAR(30),
    placed_at            TIMESTAMPTZ    NOT NULL,
    cancelled_at         TIMESTAMPTZ,
    created_at           TIMESTAMPTZ    NOT NULL,
    updated_at           TIMESTAMPTZ    NOT NULL,
    version              BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT fk_orders_known_user FOREIGN KEY (user_id) REFERENCES known_user (user_id),
    CONSTRAINT ck_orders_status CHECK (status IN ('PLACED', 'CANCELLED')),
    CONSTRAINT ck_orders_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_orders_total_amount CHECK (total_amount >= 0),
    CONSTRAINT ck_orders_cancellation_reason
        CHECK (cancellation_reason IS NULL OR cancellation_reason IN ('CUSTOMER_REQUEST', 'USER_DEACTIVATED')),
    CONSTRAINT ck_orders_cancellation_consistent CHECK (
        (status = 'PLACED' AND cancelled_at IS NULL AND cancellation_reason IS NULL)
        OR (status = 'CANCELLED' AND cancelled_at IS NOT NULL AND cancellation_reason IS NOT NULL))
);

-- Serves the foreign key, "orders of a user" listings, and "open orders of a user" on UserDeactivated.
CREATE INDEX ix_orders_user_id_status ON orders (user_id, status);
CREATE INDEX ix_orders_status ON orders (status);

CREATE TABLE order_line (
    id          BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    order_id    BIGINT         NOT NULL,
    line_no     INT            NOT NULL,
    sku         VARCHAR(64)    NOT NULL,
    quantity    INT            NOT NULL,
    unit_price  NUMERIC(19, 4) NOT NULL,
    line_total  NUMERIC(19, 4) NOT NULL,
    CONSTRAINT pk_order_line PRIMARY KEY (id),
    CONSTRAINT fk_order_line_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    -- also the index for the foreign key (order_id is its leading column)
    CONSTRAINT uk_order_line_order_line_no UNIQUE (order_id, line_no),
    CONSTRAINT ck_order_line_line_no CHECK (line_no >= 1),
    CONSTRAINT ck_order_line_sku CHECK (char_length(btrim(sku)) BETWEEN 1 AND 64),
    CONSTRAINT ck_order_line_quantity CHECK (quantity BETWEEN 1 AND 1000),
    CONSTRAINT ck_order_line_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_order_line_line_total CHECK (line_total >= 0)
);
